package Strings;
import java.util.*;
public class StringsBasicCommands {
    public static void main(String[] args){
//        Concatenation
        String first_Name = "Deepan";
        String last_Name = "Maurya";
        String Full_Name  = first_Name + " " + last_Name;
        System.out.println("The concatenate sentence is : " + Full_Name);
//        CharAt method
        System.out.println("Char at index 1 is : " + Full_Name.charAt(1));
    }
}
