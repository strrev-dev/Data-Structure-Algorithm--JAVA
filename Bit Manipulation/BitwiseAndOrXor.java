public class BitwiseAndOrXor {
    public static void main(String[] args){
        System.out.println("Bitwise And of  5 & 6 is : " +  (5 & 6));
        System.out.println("Bitwise And of  5 | 6 is : " +  (5 | 6));
        System.out.println("Bitwise And of  5 ^ 6 is : " +  (5 ^ 6)); //In XOR same bit gives 0 as output
    }
}
